#!/usr/bin/env python3
"""Classify every test class of PEMS.Tests by what it needs (SCRUM-393), so a session knows which classes are database-free and fast and which need SQL Server.

    python tools/test-gates/classify.py            # write tools/test-gates/test-classes.md and print the counts
    python tools/test-gates/classify.py --check    # exit 1 when the committed file is out of date

Tiers (first match wins, detected from the source of the file):
  sql         uses a real SQL Server (DisposableSqlDatabase, ThrowawaySqlServer, SqlFaultInjection, UseSqlServer): runs only where a local SQLEXPRESS exists
  host        starts the application or a web host (WebApplicationFactory, TestServer, RazorViewRenderer): slower, no database server
  in-memory   builds an EF in-memory context (PemsDbContextFactory, UseInMemoryDatabase)
  source-scan reads the source tree (SourceTree, File.ReadAllText, Directory.EnumerateFiles): cheap per test, shares SourceTree's cache
  free        none of the above: plain unit tests
"""
import os, re, sys, collections

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TESTS = os.path.join(ROOT, 'PEMS.Tests')
OUT = os.path.join(os.path.dirname(__file__), 'test-classes.md')
RULES = [
    ('sql', re.compile(r'DisposableSqlDatabase|ThrowawaySqlServer|SqlFaultInjection|UseSqlServer|SqlSchemaSnapshot')),
    ('host', re.compile(r'WebApplicationFactory|TestServer|RazorViewRenderer')),
    ('in-memory', re.compile(r'PemsDbContextFactory|UseInMemoryDatabase|RcmTestFactory|OrgSeed')),
    ('source-scan', re.compile(r'SourceTree|File\.ReadAllText|File\.ReadLines|Directory\.EnumerateFiles|Directory\.GetFiles')),
]
CLASS = re.compile(r'^\s*(?:public\s+)?(?:sealed\s+)?(?:static\s+)?class\s+(\w+)', re.M)
TEST = re.compile(r'\[(?:Fact|Theory)')

def classify(text):
    for tier, rx in RULES:
        if rx.search(text): return tier
    return 'free'

def build():
    rows = []
    for dp, dn, fn in os.walk(TESTS):
        dn[:] = [d for d in dn if d not in ('bin', 'obj', 'TestResults')]
        for f in fn:
            if not f.endswith('.cs'): continue
            p = os.path.join(dp, f); t = open(p, encoding='utf-8-sig').read()
            if not TEST.search(t): continue
            tests = len(TEST.findall(t))
            names = CLASS.findall(t)
            rel = os.path.relpath(p, TESTS).replace(os.sep, '/')
            rows.append((classify(t), rel, ', '.join(names[:3]), tests))
    return sorted(rows)

def render(rows):
    by = collections.Counter(); n = collections.Counter()
    for tier, _, _, t in rows: by[tier] += 1; n[tier] += t
    out = ['# Test classes by tier (generated by tools/test-gates/classify.py, SCRUM-393)', '',
           'Do not edit; run `python tools/test-gates/classify.py`. A class moves tier when its source starts or stops using the marker named in the script.', '',
           '| Tier | Files | Tests (Fact/Theory attributes) |', '|---|---|---|']
    for tier in ('free', 'source-scan', 'in-memory', 'host', 'sql'):
        out.append('| %s | %d | %d |' % (tier, by[tier], n[tier]))
    out += ['', '| Tier | File | Classes | Tests |', '|---|---|---|---|']
    out += ['| %s | %s | %s | %d |' % r for r in rows]
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    rows = build(); text = render(rows)
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(OUT) else ''
        sys.exit(0 if cur == text else 1)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(text.split('\n\n')[2])
