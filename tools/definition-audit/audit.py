#!/usr/bin/env python3
"""Inventory of everything that is still compiled code between the user and the database (guideline 04, "definition-only model").

    python tools/definition-audit/audit.py            # print the summary
    python tools/definition-audit/audit.py --write    # also write plan/sheets/definition-inventory.md (the table every conversion issue is checked against)

Run it at the start of any migration or backlog-planning work block, BEFORE creating issues: a backlog built from memory missed 150+ tasks (2026-11-19).
It counts, per controller: actions by kind (write, file, json, view), inline DbContext use (needs a service first) and the view folder size;
and globally: views, inline scripts, TempData uses, definitions already shipped by kind. Pure file scan: no build, no database.
"""
import os, re, sys, json, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "PEMS.Web"
DEFS = ROOT / "PEMS.Persistence" / "Definitions" / "System"
# controllers that stay code by decision (generic hosts, auth, infra); everything else must be converted or classified (SCRUM-628)
HOSTS = {"FormHost", "PageHost", "DataHost", "Culture", "Theme", "NavigationBadge", "Files", "WebAuthn", "RecoveryCodes", "BreakGlass",
         "AccountRecovery", "Account", "ComingSoon", "SearchApi"}
ACTION = re.compile(r'((?:[ \t]*\[[^\]\n]*\][ \t]*\n)*)[ \t]*public\s+(?:async\s+)?(?:Task<)?(\w+(?:<[^>\n]*>)?)>?\s+(\w+)\s*\(([^)]*)\)\s*\n?\s*\{')


def scan_controllers():
    out = []
    for p in sorted(WEB.rglob("*Controller.cs")):
        if {"bin", "obj"} & set(p.parts):
            continue
        s = p.read_text(encoding="utf-8-sig")
        name = p.stem[: -len("Controller")]
        area = next((a for a in ("Admin", "Warehouse") if f"Areas{os.sep}{a}" in str(p)), "")
        acts = collections.Counter()
        n = 0
        for m in ACTION.finditer(s):
            attrs, ret, an, _ = m.groups()
            if ret in ("void", "bool", "string", "int") or an == "Dispose":
                continue
            body = s[m.end(): m.end() + 2500]
            write = any(v in attrs for v in ("HttpPost", "HttpPut", "HttpDelete"))
            kind = ("file" if re.search(r"\bFile\(|PhysicalFile|FileStreamResult", body) else
                    "json" if ret == "JsonResult" or re.search(r"\bJson\(|\bOk\(", body[:1500]) else
                    "view" if re.search(r"\bView\(|PartialView\(", body) else "redirect")
            acts["write" if write else "read"] += 1
            acts[kind] += 1
            n += 1
        inline_db = len(re.findall(r"\b_?(?:context|db|dbContext)\.", s)) if "PEMSDbContext" in s else 0
        out.append({"area": area, "name": name, "actions": n, "write": acts["write"], "file": acts["file"], "json": acts["json"],
                    "inline_db": inline_db, "host": name in HOSTS or name.endswith("Api"), "path": str(p.relative_to(ROOT))})
    return out


def global_counts():
    views = list(WEB.rglob("*.cshtml"))
    views = [v for v in views if not {"bin", "obj"} & set(v.parts)]
    inline_scripts = sum(1 for v in views if "<script" in v.read_text(encoding="utf-8-sig", errors="ignore"))
    tempdata = sum(p.read_text(encoding="utf-8-sig", errors="ignore").count("TempData[") for p in WEB.rglob("*.cs") if not {"bin", "obj"} & set(p.parts))
    shipped = {d.name: sum(1 for _ in d.rglob("*.json")) for d in DEFS.iterdir() if d.is_dir()} if DEFS.exists() else {}
    return {"views": len(views), "views_with_inline_script": inline_scripts, "tempdata_uses": tempdata, "definitions_shipped": shipped}


def main():
    ctrls = scan_controllers()
    g = global_counts()
    todo = [c for c in ctrls if not c["host"]]
    print("controllers:", len(ctrls), "| to convert:", len(todo), "| hosts/static:", len(ctrls) - len(todo))
    print("actions:", sum(c["actions"] for c in ctrls), "| writes:", sum(c["write"] for c in ctrls), "| file results:", sum(c["file"] for c in ctrls),
          "| json:", sum(c["json"] for c in ctrls))
    print("controllers with inline DbContext (need a service first):", sum(1 for c in todo if c["inline_db"]))
    print(json.dumps(g, ensure_ascii=False))
    if "--write" in sys.argv:
        lines = ["# Definition inventory (generated by tools/definition-audit/audit.py)", "",
                 "Every controller is converted to definitions, or is a host/static by decision. Do not edit by hand; rerun the tool.", "",
                 "```", json.dumps(g, ensure_ascii=False, indent=1), "```", "",
                 "| Area | Controller | Actions | Writes | File | Json | Inline DB refs | Decision |", "|---|---|---|---|---|---|---|---|"]
        for c in ctrls:
            lines.append("| %s | %s | %d | %d | %d | %d | %d | %s |" % (c["area"] or "-", c["name"], c["actions"], c["write"], c["file"], c["json"], c["inline_db"],
                                                                      "host/static" if c["host"] else "convert"))
        out = ROOT / "plan" / "sheets" / "definition-inventory.md"
        out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
